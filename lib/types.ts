export interface Tariff {
  /** Уникальный идентификатор тарифа */
  id: string;
  /** Название периода (например, "1 месяц", "Навсегда") */
  period: string;
  /** Цена со скидкой (если действует акция), в рублях */
  price: number;
  /** Полная цена без скидки, в рублях */
  full_price: number;
  /** Признак рекомендуемого/хитового тарифа */
  is_best: boolean;
  /** Краткое описание тарифа для карточки */
  text: string;
}
